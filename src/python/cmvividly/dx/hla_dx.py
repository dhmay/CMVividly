class BreadthHlaClassifierCmvPos(AbstractBreadthClassifier):
    """Classifies HLA allele status for a specified allele from TCR repertoire breadth
    on the CMV ECOcluster TCRs with that HLA association.
    This type of classifier should *only* be used on repertoires determined to be
    from CMV+ donors.
    """
    def __init__(self, allele: str) -> None:
        """Initialize the classifier with the CMV ECOcluster TCRs and ROC data.
        Args:
            allele (str): The HLA allele to classify.
        """
        pdf_cmv_ecocluster = load_cmv_ecocluster_2026()
        pdf_cmv_eco_this_allele = pdf_cmv_ecocluster[pdf_cmv_ecocluster['hla'] == allele]
        data_dict_this_allele = ALLELE_DATA_MAP[allele]
        self.initialize(
            pdf_tcrs=pdf_cmv_eco_this_allele,
            breadth_roc_thresholds=data_dict_this_allele['thresholds'],
            breadth_roc_tpr=data_dict_this_allele['tpr'],
            breadth_roc_fpr=data_dict_this_allele['fpr'],
            breadth_max_f1_threshold=data_dict_this_allele['max_f1_thresh'],
            n_pos_breadth=data_dict_this_allele['n_pos'],
            n_neg_breadth=data_dict_this_allele['n_neg'],
        )
        self.auroc = data_dict_this_allele['auroc']


class AllHlaAlleleClassifierCmvPos:
    """Classifier for all HLA alleles we have the capability to classify.
    Should only be used on repertoires known to be CMV+
    """
    def __init__(self) -> None:
        """Initialize the classifier with the CMV ECOcluster TCRs and ROC data for all alleles."""
        self.allele_classifiers = {}
        for allele in ALLELE_DATA_MAP.keys():
            self.allele_classifiers[allele] = BreadthHlaClassifierCmvPos(allele)
        self.alleles = list(self.allele_classifiers.keys())

    def classify_cmvpos_repertoire(self, pdf_repertoire_tcrs: pd.DataFrame) -> pd.DataFrame:
        """Classify a repertoire. Only works for repertoires known to be CMV+.

        Args:
            pdf_repertoire_tcrs (pd.DataFrame): DataFrame of all TCRs for one repertoire, with a "tcr" column

        Returns:
            pd.DataFrame: DataFrame with classification results for each HLA allele.
        """
        allele_dx_rows = []
        for allele in self.alleles:
            allele_dx_dict = self.allele_classifiers[allele].classify_repertoire(pdf_repertoire_tcrs)
            allele_dx_dict["hla"] = allele
            allele_dx_rows.append(allele_dx_dict)
        pdf_allele_dx = pd.DataFrame(allele_dx_rows)
        # move "hla" to the first column
        pdf_allele_dx = pdf_allele_dx[["hla"] + [col for col in pdf_allele_dx.columns if col != "hla"]]
        return pdf_allele_dx